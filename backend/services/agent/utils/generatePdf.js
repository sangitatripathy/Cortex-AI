import PDFDocument from "pdfkit";

export const generatePDF = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margin: 50,
      info: {
        Author: "CortexAI",
        Title: data.title || "CortexAI Document",
        Creator: "CortexAI",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));

    doc.on("end", () => {
      resolve(Buffer.concat(chunks));
    });

    doc.on("error", (error) => {
      reject(error);
    });

    // Title
    doc
      .fontSize(28)
      .fillColor("#111827")
      .text(data.title || "Untitled Document", {
        align: "center",
      });

    // Subtitle
    if (data.subtitle) {
      doc.moveDown(0.5);

      doc
        .fontSize(12)
        .fillColor("#6B7280")
        .text(data.subtitle, {
          align: "center",
        });
    }

    doc.moveDown(2);

    // Sections
    data?.sections?.forEach((section) => {
      // Heading
      doc
        .fontSize(18)
        .fillColor("#111827")
        .text(section.heading || "");

      doc.moveDown(0.5);

      // Points
      section?.points?.forEach((point) => {
        doc
          .fontSize(11)
          .fillColor("#374151")
          .text(`• ${point}`, {
            lineGap: 5,
          });

        doc.moveDown(0.2);
      });

      doc.moveDown(1);
    });

    // Footer
    doc
      .fontSize(10)
      .fillColor("#9CA3AF")
      .text("Generated By CortexAI", {
        align: "center",
      });

    doc.end();
  });
};